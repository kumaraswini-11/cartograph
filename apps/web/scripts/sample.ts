// `pnpm --filter web sample`: writes the map's samples (spec 003 plan D-06,
// spec 005 plan D-07): for each golden repository at its pinned commit, the
// map input derived from the parser's and detection's results unchanged
// (C-02), committed, so every deployment shows the same maps until `008`
// stores real analyses. Prints each sample's insights, which is how a cycle
// is checked by hand (spec 005, AC-03). The network is this script's; the app
// never loads the parser.
import { writeFileSync } from "node:fs"
import { join } from "node:path"

import { detectFrameworks } from "@workspace/frameworks"
import { checkout } from "@workspace/golden"
import {
  insights,
  sentenceOf,
  sentenceText,
  toMapInput,
} from "@workspace/graph"
import { isTooLarge, parseRepository } from "@workspace/parser"

import { SAMPLES } from "../src/sample/samples.ts"

for (const sample of SAMPLES) {
  const { repository, commit } = sample
  const directory = await checkout(repository, commit)
  const parsed = parseRepository(directory)
  if (isTooLarge(parsed)) throw new Error(`${repository} is too large`)
  const input = toMapInput(
    { repository, commit },
    parsed,
    detectFrameworks(directory, parsed)
  )

  writeFileSync(
    join(import.meta.dirname, "..", "src", "sample", `${sample.name}.gen.ts`),
    [
      "// Generated by scripts/sample.ts (`pnpm --filter web sample`); do not edit.",
      'import type { MapInput } from "@workspace/graph"',
      "",
      `export const SAMPLE_MAP: MapInput = ${JSON.stringify(input, null, 2)}`,
      "",
    ].join("\n")
  )
  console.log(
    `Wrote ${repository} @ ${commit.slice(0, 7)}: ${input.files.length} files, ${input.edges.length} edges, ${input.routes.length} routes`
  )
  for (const insight of insights(input)) {
    console.log(`  ${sentenceText(sentenceOf(insight))}`)
  }
}
