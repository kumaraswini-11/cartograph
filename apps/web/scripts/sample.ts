// `pnpm --filter web sample`: writes the map's sample (spec 003, plan D-06):
// the map input for one golden repository at its pinned commit, derived from
// the parser's and detection's results unchanged (C-02) and committed, so
// every deployment shows the same map until `008` stores real analyses. The
// network is this script's; the app never loads the parser.
import { writeFileSync } from "node:fs"
import { join } from "node:path"

import { detectFrameworks } from "@workspace/frameworks"
import { checkout } from "@workspace/golden"
import { toMapInput } from "@workspace/graph"
import { isTooLarge, parseRepository } from "@workspace/parser"

const REPOSITORY = "shadcn-ui/taxonomy"
const COMMIT = "298a8857c7128a0d121e7f699dfd729f23b3966d"
const OUT = join(import.meta.dirname, "..", "src", "sample", "map.gen.ts")

const directory = await checkout(REPOSITORY, COMMIT)
const parsed = parseRepository(directory)
if (isTooLarge(parsed)) throw new Error(`${REPOSITORY} is too large`)
const input = toMapInput(
  { repository: REPOSITORY, commit: COMMIT },
  parsed,
  detectFrameworks(directory, parsed)
)

writeFileSync(
  OUT,
  [
    "// Generated by scripts/sample.ts (`pnpm --filter web sample`); do not edit.",
    'import type { MapInput } from "@workspace/graph"',
    "",
    `export const SAMPLE_MAP: MapInput = ${JSON.stringify(input, null, 2)}`,
    "",
  ].join("\n")
)
console.log(
  `Wrote ${REPOSITORY} @ ${COMMIT.slice(0, 7)}: ${input.files.length} files, ${input.edges.length} edges`
)
